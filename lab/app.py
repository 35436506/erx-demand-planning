"""ERX Forecasting Lab — entry point (bilingual).  Run:  streamlit run app.py

Language: ?lang=en | ?lang=vi in the URL (the website adds it), or the switch at the top of the sidebar.
The English pages (home_en.py, lab_pages_en/, lab_common_en.py, dpkit_en/) are generated by
tools/build_lab.py from the Vietnamese source — edit the Vietnamese files and the maps in i18n/lab/, then rebuild.
"""
import streamlit as st

st.set_page_config(page_title="ERX Forecasting Lab", page_icon="📈", layout="wide")

# ---- language: URL first, then what this session already chose
q = st.query_params.get("lang")
if q in ("vi", "en"):
    st.session_state["lang"] = q
lang = st.session_state.get("lang", "vi")


def _switch():
    st.session_state["lang"] = "en" if st.session_state["_lang_pick"] == "English" else "vi"
    st.query_params["lang"] = st.session_state["lang"]


st.sidebar.radio("Ngôn ngữ / Language", ["Tiếng Việt", "English"], index=1 if lang == "en" else 0,
                 horizontal=True, key="_lang_pick", on_change=_switch)
if st.query_params.get("lang") != lang:
    st.query_params["lang"] = lang

TITLES = {
    "vi": ["Trang chủ", "Buổi 1 · Phân cấp dự báo", "Buổi 2 · Làm sạch dữ liệu", "Buổi 3 · Mốc & sai số", "Buổi 4 · San bằng mũ",
           "Buổi 5 · Mùa vụ & Tết", "Buổi 6 · Hồi quy & khuyến mãi", "Buổi 7 · Danh mục & Croston", "Buổi 8 · Demand Review & FVA",
           "Buổi 9 · Tồn kho & S&OP", "Buổi 10 · Capstone"],
    "en": ["Home", "Session 1 · Forecasting hierarchy", "Session 2 · Data cleaning", "Session 3 · Benchmarks & error",
           "Session 4 · Exponential smoothing", "Session 5 · Seasonality & Tết", "Session 6 · Regression & promotions",
           "Session 7 · Portfolio & Croston", "Session 8 · Demand Review & FVA", "Session 9 · Inventory & S&OP", "Session 10 · Capstone"],
}
FILES = ["1_Buoi1_Phan_cap.py", "2_Buoi2_Lam_sach.py", "3_Buoi3_Sai_so.py", "4_Buoi4_Smoothing.py", "5_Buoi5_Mua_vu_Tet.py",
         "6_Buoi6_Hoi_quy_KM.py", "7_Buoi7_Danh_muc.py", "8_Buoi8_FVA.py", "9_Buoi9_Ton_kho_SOP.py", "10_Buoi10_Capstone.py"]
ICONS = ["1️⃣", "2️⃣", "3️⃣", "4️⃣", "5️⃣", "6️⃣", "7️⃣", "8️⃣", "9️⃣", "🎓"]

t = TITLES[lang]
folder, home = ("lab_pages_en", "home_en.py") if lang == "en" else ("lab_pages", "home.py")
pages = [st.Page(home, title=t[0], icon="🏠", default=True)]
pages += [st.Page(f"{folder}/{f}", title=t[i + 1], icon=ICONS[i], url_path=f"buoi-{i + 1}") for i, f in enumerate(FILES)]
st.navigation(pages).run()
